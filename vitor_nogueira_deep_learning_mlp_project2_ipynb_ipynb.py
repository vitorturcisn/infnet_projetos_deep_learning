def plot_eda(image_paths, labels, classes, class_to_idx):
    """Gera e salva gráficos exploratórios da distribuição de classes e amostras."""
    sns.set_theme(style="whitegrid")

    # Gráfico de distribuição
    fig, ax = plt.subplots(figsize=(8, 5), facecolor='white')
    df_counts = pd.DataFrame({'Classe': [classes[l] for l in labels]})
