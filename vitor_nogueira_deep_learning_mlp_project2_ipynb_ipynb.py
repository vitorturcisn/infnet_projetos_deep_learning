def plot_tensorboard_metrics(log_dir: str):
    """Extrai os logs do TensorBoard e gera curvas de aprendizado."""
    event_files = [os.path.join(log_dir, f) for f in os.listdir(log_dir) if 'events.out' in f]
    if not event_files:
        print("Nenhum arquivo de log do TensorBoard encontrado.")
        return

    ea = EventAccumulator(event_files[0])
    ea.Reload()

    train_loss_tb = [s.value for s in ea.Scalars('Loss/Train')]
    val_loss_tb = [s.value for s in ea.Scalars('Loss/Val')]
    train_acc_tb = [s.value for s in ea.Scalars('Accuracy/Train')]
    val_acc_tb = [s.value for s in ea.Scalars('Accuracy/Val')]
    steps_tb = [s.step for s in ea.Scalars('Loss/Train')]

    fig, axes = plt.subplots(1, 2, figsize=(13, 4.5), facecolor='white')

    # Curva de Perda
    axes[0].set_facecolor('white')
    axes[0].plot(steps_tb, train_loss_tb, label='Train Loss', color='#0A345D', linewidth=2)
    axes[0].plot(steps_tb, val_loss_tb, label='Val Loss', color='#FF7043', linewidth=2)
    axes[0].set_title('CrossEntropy Loss', fontweight='bold')
    axes[0].set_xlabel('Época')
    axes[0].set_ylabel('Loss')
    axes[0].legend()
    axes[0].grid(True, linestyle='--', alpha=0.5)

    # Curva de Acurácia
    axes[1].set_facecolor('white')
    axes[1].plot(steps_tb, [a * 100 for a in train_acc_tb], label='Train Acc (%)', color='#1BB5D8', linewidth=2)
    axes[1].plot(steps_tb, [a * 100 for a in val_acc_tb], label='Val Acc (%)', color='#7CB342', linewidth=2)
    axes[1].set_title('Acurácia (%)', fontweight='bold')
    axes[1].set_xlabel('Época')
    axes[1].set_ylabel('Acurácia (%)')
    axes[1].legend()
    axes[1].grid(True, linestyle='--', alpha=0.5)

    plt.tight_layout()
    fig.savefig('cnn_learning_curves.png', dpi=300, bbox_inches='tight', facecolor='white')
    plt.close()

plot_tensorboard_metrics('runs/flower_resnet18_experiment')


# ==============================================================================
# 7. AVALIAÇÃO FINAL NO CONJUNTO DE TESTE
# ==============================================================================

model.load_state_dict(torch.load(checkpoint_path))
model.eval()

y_test_preds = []
with torch.no_grad():
    for X_b, _ in test_loader:
        X_b = X_b.to(device)
        out = model(X_b)
        _, preds = torch.max(out, 1)
        y_test_preds.extend(preds.cpu().numpy())

test_acc = accuracy_score(y_test, y_test_preds)

print("\n" + "=" * 60)
print(f"Acurácia no Conjunto de Teste (ResNet18): {test_acc * 100:.2f}%")
print("=" * 60)

print("\nRelatório de Classificação Detalhado:")
print(classification_report(y_test, y_test_preds, target_names=classes))

# Matriz de Confusão
fig, ax = plt.subplots(figsize=(7, 5.5), facecolor='white')
cm = confusion_matrix(y_test, y_test_preds)
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=ax, xticklabels=classes, yticklabels=classes)
ax.set_title('Matriz de Confusão (Conjunto de Teste - ResNet18)', fontweight='bold')
ax.set_xlabel('Classe Prevista')
ax.set_ylabel('Classe Real')
ax.set_facecolor('white')

plt.tight_layout()
fig.savefig('resnet18_matriz_confusao.png', dpi=300, bbox_inches='tight', facecolor='white')
plt.close()