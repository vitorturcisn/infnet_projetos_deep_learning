"""
Flower Image Classification using ResNet18 Transfer Learning
Dataset: Kaggle Flowers Recognition (5 classes)
"""

import os
import random
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from PIL import Image

import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader
from torch.utils.tensorboard import SummaryWriter
from torchvision import transforms, models
from torchvision.models import ResNet18_Weights

from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
from tensorboard.backend.event_processing.event_accumulator import EventAccumulator
import kagglehub


# ==============================================================================
# 1. CONFIGURAÇÃO GLOBAL E REPRODUTIBILIDADE
# ==============================================================================

def set_seed(seed: int = 42) -> None:
    """Define sementes aleatórias para reprodutibilidade dos experimentos."""
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    np.random.seed(seed)
    random.seed(seed)
    torch.backends.cudnn.deterministic = True

set_seed(42)
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Dispositivo de execução selecionado: {device}")


# ==============================================================================
# 2. CARREGAMENTO E Mapeamento DO DATASET
# ==============================================================================

def load_dataset():
    """Baixa e mapeia os caminhos das imagens e rótulos do Kaggle Flowers."""
    path = kagglehub.dataset_download("alxmamaev/flowers-recognition")

    classes = sorted(['daisy', 'dandelion', 'rose', 'sunflower', 'tulip'])
    class_to_idx = {cls_name: i for i, cls_name in enumerate(classes)}

    base_dir = path
    for root, dirs, _ in os.walk(path):
        if set(classes).issubset(set(dirs)):
            base_dir = root
            break

    image_paths = []
    labels = []

    for cls_name in classes:
        cls_dir = os.path.join(base_dir, cls_name)
        if os.path.exists(cls_dir):
            for fname in os.listdir(cls_dir):
                if fname.lower().endswith(('.jpg', '.jpeg', '.png')):
                    image_paths.append(os.path.join(cls_dir, fname))
                    labels.append(class_to_idx[cls_name])

    return image_paths, labels, classes, class_to_idx

image_paths, labels, classes, class_to_idx = load_dataset()
print(f"Dataset carregado: {len(image_paths)} imagens distribuídas em {len(classes)} classes.")


# ==============================================================================
