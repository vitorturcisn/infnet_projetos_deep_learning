plot_eda(image_paths, labels, classes, class_to_idx)


# ==============================================================================
# 4. PREPARAÇÃO DOS DADOS E PIPELINE DE TRANSFORMAÇÃO
# ==============================================================================

class PyTorchFlowersDataset(Dataset):
    """Dataset customizado para carregamento e transformação de imagens de flores."""
    def __init__(self, image_paths, labels, transform=None):
        self.image_paths = image_paths
        self.labels = labels
        self.transform = transform

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        img_path = self.image_paths[idx]
        image = Image.open(img_path).convert('RGB')
        label = self.labels[idx]

        if self.transform:
            image = self.transform(image)

        return image, label


# Divisão estratificada dos dados (80% treino, 10% validação, 10% teste)
X_train_paths, X_temp_paths, y_train, y_temp = train_test_split(
    image_paths, labels, test_size=0.20, random_state=42, stratify=labels
)
X_val_paths, X_test_paths, y_val, y_test = train_test_split(
    X_temp_paths, y_temp, test_size=0.50, random_state=42, stratify=y_temp
)

# Definição das transformações e aumento de dados
mean_norm = [0.485, 0.456, 0.406]
std_norm = [0.229, 0.224, 0.225]

train_transform = transforms.Compose([
    transforms.RandomResizedCrop(224, scale=(0.8, 1.0)),
    transforms.RandomHorizontalFlip(p=0.5),
    transforms.RandomRotation(degrees=20),
    transforms.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.2, hue=0.05),
    transforms.ToTensor(),
    transforms.Normalize(mean=mean_norm, std=std_norm)
])

val_test_transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(mean=mean_norm, std=std_norm)
])

# Inicialização dos DataLoaders
train_dataset = PyTorchFlowersDataset(X_train_paths, y_train, transform=train_transform)
val_dataset = PyTorchFlowersDataset(X_val_paths, y_val, transform=val_test_transform)
test_dataset = PyTorchFlowersDataset(X_test_paths, y_test, transform=val_test_transform)

batch_size = 32
train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True, num_workers=2)
val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False, num_workers=2)
test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False, num_workers=2)


# ==============================================================================
# 5. ARQUITETURA E TREINAMENTO DO MODELO (TRANSFER LEARNING)
# ==============================================================================

def build_resnet18(num_classes: int = 5):
    """Carrega ResNet18 pré-treinada e substitui a camada de classificação."""
    model = models.resnet18(weights=ResNet18_Weights.DEFAULT)
    in_features = model.fc.in_features
    model.fc = nn.Sequential(
        nn.Dropout(p=0.3),
        nn.Linear(in_features, num_classes)
    )
    return model

model = build_resnet18(num_classes=len(classes)).to(device)

criterion = nn.CrossEntropyLoss()
optimizer = optim.AdamW(model.parameters(), lr=1e-4, weight_decay=1e-4)
scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.5, patience=2)

writer = SummaryWriter(log_dir='runs/flower_resnet18_experiment')
epochs = 15
best_val_loss = float('inf')
checkpoint_path = 'best_flower_resnet18.pt'

print("Iniciando o treinamento do modelo ResNet18...")

for epoch in range(1, epochs + 1):
    # Loop de Treino
    model.train()
    train_loss, train_correct, total_train = 0.0, 0, 0
    for X_b, y_b in train_loader:
        X_b, y_b = X_b.to(device), y_b.to(device)
        optimizer.zero_grad()
        outputs = model(X_b)
        loss = criterion(outputs, y_b)
        loss.backward()
        optimizer.step()

        train_loss += loss.item() * X_b.size(0)
        _, preds = torch.max(outputs, 1)
        train_correct += (preds == y_b).sum().item()
        total_train += y_b.size(0)

    ep_train_loss = train_loss / total_train
    ep_train_acc = train_correct / total_train

    # Loop de Validação
    model.eval()
    val_loss, val_correct, total_val = 0.0, 0, 0
    with torch.no_grad():
        for X_b, y_b in val_loader:
            X_b, y_b = X_b.to(device), y_b.to(device)
            outputs = model(X_b)
            loss = criterion(outputs, y_b)

            val_loss += loss.item() * X_b.size(0)
            _, preds = torch.max(outputs, 1)
            val_correct += (preds == y_b).sum().item()
            total_val += y_b.size(0)

    ep_val_loss = val_loss / total_val
    ep_val_acc = val_correct / total_val

    scheduler.step(ep_val_loss)

    writer.add_scalar('Loss/Train', ep_train_loss, epoch)
    writer.add_scalar('Loss/Val', ep_val_loss, epoch)
    writer.add_scalar('Accuracy/Train', ep_train_acc, epoch)
    writer.add_scalar('Accuracy/Val', ep_val_acc, epoch)

    if ep_val_loss < best_val_loss:
        best_val_loss = ep_val_loss
        torch.save(model.state_dict(), checkpoint_path)

    print(f"Época [{epoch:02d}/{epochs:02d}] | "
          f"Train Loss: {ep_train_loss:.4f} - Train Acc: {ep_train_acc * 100:.2f}% | "
          f"Val Loss: {ep_val_loss:.4f} - Val Acc: {ep_val_acc * 100:.2f}%")

writer.close()
print(f"Treinamento concluído. Checkpoint do melhor modelo salvo em: {checkpoint_path}")


